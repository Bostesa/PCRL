"""Generated tables of the PCRL finite-output solver-adequacy campaign (label-free; saved records only).

    python3 -m fsa.report        writes results/<campaign>/tables/{OBJECTIVE_AUDIT,EXACT_REFERENCE,SOLVER_COMPARISON}_TABLES.md

Every number in these tables is read from a committed record: audit/, source/, nested/, replay/, decisions/ and the exact-reference
investigator's files. Development evidence on previously used records; cached MODEL_FIT statistics are derived from training labels.
"""
from __future__ import annotations
import json
import math
import sys
from pathlib import Path

from . import common as C

R = C.RESULTS
GRID = (0.25, 0.5, 1.0, 2.0, 4.0, 8.0)
LAWS = ('A_null', 'B_collide', 'C_distinct', 'D_witness', 'E_distinct_N200')


def _j(p):
    return json.loads(Path(p).read_text())


def _f(x, d=4, sign=False):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return '-'
    return f'{x:+.{d}f}' if sign else f'{x:.{d}f}'


def audit_tables():
    out = ['# Objective audit tables (generated by `python3 -m fsa.report`)', '',
           'Cached MODEL_FIT out-of-fold statistics (derived from MODEL_FIT training labels); the saved finite-routing releases. '
           'Records: `audit/OBJECTIVE_AUDIT_V<v>.json`.', '',
           '## A. The original chain (traced; reproduces the saved partitions)', '',
           '| Family | Version | Reproduces saved partition | Accepted objective strictly decreasing | Lloyd steps / accepted | '
           'Refresh steps that raised the objective | Largest refresh change |', '|---|---|---|---|---|---|---|']
    for fam in ('PRC', 'HQ'):
        for v in C.VERSIONS:
            a = _j(R / 'audit' / f'OBJECTIVE_AUDIT_V{v}.json')[f'{fam}_chain']
            out.append(f"| {fam} | {v} | {a['reproduces_saved_partition']} | {a['accepted_objective_strictly_decreasing']} | "
                       f"{a['n_steps']} / {a['n_accepted']} | {a['refresh_raised_objective_steps']} | {_f(a['refresh_delta_max'], 8, True)} |")
    out += ['', '## B. Routing proposal score against the acceptance objective along the tilt line (final refreshed book, strength 8)', '',
            '| Family | Version | Intervals (distinct deployable partitions) | Spearman: proposal dependence vs objective dependence | '
            'Spearman: proposal total vs objective | Current objective | Best on the refreshed line (tilt) |', '|---|---|---|---|---|---|---|']
    for fam in ('PRC', 'HQ'):
        for v in C.VERSIONS:
            t = _j(R / 'audit' / f'OBJECTIVE_AUDIT_V{v}.json')[f'{fam}_tilt_line_at_8']
            b = t['best_interval']
            out.append(f"| {fam} | {v} | {t['n_intervals']:,} | {_f(t['spearman_dependence_proposal_vs_objective'], 3)} | "
                       f"{_f(t['spearman_total_proposal_vs_objective'], 3)} | {_f(t['current_objective'], 6)} | {_f(b['objective'], 6)} "
                       f"({_f(0.5 * (b['t_lo'] + b['t_hi']), 4)}) |")
    out += ['', '## C. Emitted B1 tables against the search prototypes (training out-of-fold posteriors)', '',
            '| Release | Version | Largest abs(table - prototype) | Occupation CE: prototypes / emitted | Income CE: prototypes / emitted | '
            'Guard: prototypes / emitted |', '|---|---|---|---|---|---|']
    for name, key in (('PRC_S2', 'PRC_emitted_vs_proto'), ('HQ_S2', 'HQ_emitted_vs_proto'), ('TWB_C64', 'TWIN_emitted_vs_proto')):
        for v in C.VERSIONS:
            e = _j(R / 'audit' / f'OBJECTIVE_AUDIT_V{v}.json')[key]
            out.append(f"| {name} | {v} | {_f(e['emitted_minus_proto_max_abs'], 4)} | {_f(e['proto_ce_occupation'], 6)} / "
                       f"{_f(e['emitted_ce_occupation'], 6)} | {_f(e['proto_ce_income'], 6)} / {_f(e['emitted_ce_income'], 6)} | "
                       f"{_f(e.get('guard_proto'), 5)} / {_f(e.get('guard_emitted'), 5)} |")
    out += ['', '## D. Runtime routing consistency and expressivity (label-free)', '',
            '| Version | Joint-cell agreement, in-sample vs out-of-fold, MODEL_FIT rows (TWB_C64 / PRC_S2 / HQ_S2) | Distinct six-field '
            'support states | Distinct task-score vectors | Share of people whose task scores are shared with another state |',
            '|---|---|---|---|---|']
    for v in C.VERSIONS:
        a = _j(R / 'audit' / f'OBJECTIVE_AUDIT_V{v}.json')
        ag = ' / '.join(_f(a[f'runtime_{c}']['model_fit_rows_joint_cell_agreement_insample_vs_oof'], 3) for c in ('TWB_C64', 'PRC_S2', 'HQ_S2'))
        x = a['expressivity']
        out.append(f"| {v} | {ag} | {x['distinct_support_states']:,} | {x['distinct_task_score_vectors']:,} | "
                   f"{_f(x['share_of_people_whose_task_scores_are_shared_with_another_support_state'], 4)} |")
    adv = _j(R / 'decisions' / 'ADVANCEMENT.json')
    out += ['', '## E. Defect route (frozen rule `route_d`)', '', f"Label: **{adv['result']['labels']['D']['_']}**. Examined claims:", '']
    for c in adv['input']['D']['claims']:
        out.append(f"- `{c['approximation']}` ({c['location']}): {c['evidence']}. Rule label: `NOT_A_DEFECT_DOCUMENTED_APPROXIMATION`.")
    return out


def exact_tables():
    res = _j(R / 'roles' / 'exact_reference' / 'RESULTS_V1.json')
    st = _j(R / 'roles' / 'exact_reference' / 'STEP5_V1.json')
    out = ['# Exact-reference tables (generated by `python3 -m fsa.report`)', '',
           'Registered invented laws (`roles/exact_reference/LAWS.md`, laws.json; committed c27a91477 at 02:42:16Z before any run). '
           'Exact population quantities; exact Bayes AUC of the emitted values (identical vectors merged). Seed 1 equals seed 0 in every '
           'cell. Records: RESULTS_V1.json, NARROW_V1/V2.json, ENUM_V1/V2.json, STEP5_V1.json.', '',
           '## A. Per law: full release, decision-only release, twin, witness and the relaxation scope', '',
           '| Law | Full posterior pair AUC | Decision-only pair AUC (feasible) | Witness pair AUC (feasible) | Partitions enumerated '
           '(feasible) |', '|---|---|---|---|---|']
    for law in LAWS:
        x = res['laws'][law]
        wit = x.get('witness')
        out.append(f"| {law} | {_f(x['full']['auc_pair'])} | {_f(x['decision_only']['auc_pair'])} ({x['decision_only']['feasible']}) | "
                   f"{(_f(wit['auc_pair']) + ' (' + str(wit['feasible']) + ')') if wit else '-'} | "
                   f"{x['enum']['n_assignments']:,} ({x['enum']['n_feasible_assignments']:,}) |")
    out += ['', '## B. Original solver, SV1 and the same-class reference per strength (seed 0)', '',
            '| Law | Strength | Original: J / pair AUC / feasible | SV1: J / pair AUC / feasible | SV1 - original J | Reference: J (class) | '
            'Unrestricted relaxation J (reported only) |', '|---|---|---|---|---|---|---|']
    for law in LAWS:
        for lam in GRID:
            c = st['cells'][f'{law}:seed0@{lam}']
            o, s = c['points']['original_traced'], c['points']['SV1']
            ref, unr = c.get('reference') or {}, c.get('unrestricted') or {}
            out.append(f"| {law} | {lam} | {_f(o['J'], 5)} / {_f(o['auc']['pair'])} / {o['feasible']} | {_f(s['J'], 5)} / "
                       f"{_f(s['auc']['pair'])} / {s['feasible']} | {_f(s['J'] - o['J'], 5, True)} | {_f(ref.get('J'), 5)} "
                       f"({ref.get('class', '-')}) | {_f(unr.get('J'), 5)} |")
    e = st.get('route_e_PROVISIONAL') or {}
    adv = _j(R / 'decisions' / 'ADVANCEMENT.json')
    out += ['', f"Route E (frozen `route_e`, source fields from the measured source check): **{adv['result']['labels']['E']['SV1']}** "
                f"(its own label E_ADVANCES, superseded by route S under RULES 5.2). SV1_first equals SV1 in every cell (equal-effort control)."]
    return out


def solver_tables():
    out = ['# Solver comparison tables (generated by `python3 -m fsa.report`)', '',
           'Records: `source/SOURCE_CHECK_V<v>.json` (full-pool cached MODEL_FIT out-of-fold statistics, derived from training labels), '
           '`nested/NESTED_SOLVERS_V<v>.json` (MODEL_FIT nested held-out: 5 outer household folds, refitted teachers), '
           '`decisions/ROUTE_S_INPUT.json`, `decisions/ADVANCEMENT.json`, `decisions/EQUAL_EFFORT_ATTRIBUTION.json`. MODEL_SELECT was not '
           'read by any stage.', '',
           '## A. Fitted objective on the full pool (lower is better for the stated objective; it is not a usefulness measure)', '',
           '| Family | Version | Strength | Original J | SV1 J | SV1_first J (control) | SV1 - original | Re-routed vs twin: original / SV1 '
           '| Fitted pi pair MI: original / SV1 | Emitted training CE: original / SV1 |', '|---|---|---|---|---|---|---|---|---|---|']
    for fam in ('PRC', 'HQ'):
        for v in C.VERSIONS:
            s = _j(R / 'source' / f'SOURCE_CHECK_V{v}.json')['runs']
            for lam in GRID:
                o, n, c = (s[f'{fam}|{x}']['per_strength'][str(lam)] for x in ('original', 'SV1', 'SV1_first'))
                out.append(f"| {fam} | {v} | {lam} | {_f(o['objective'], 6)} | {_f(n['objective'], 6)} | {_f(c['objective'], 6)} | "
                           f"{_f(n['objective'] - o['objective'], 6, True)} | {_f(o['rerouted_vs_twin'], 3)} / {_f(n['rerouted_vs_twin'], 3)} | "
                           f"{_f(o['fitted_pi_pair_mi'], 5)} / {_f(n['fitted_pi_pair_mi'], 5)} | "
                           f"{_f(o['emitted_ce_income'] + o['emitted_ce_occupation'], 5)} / {_f(n['emitted_ce_income'] + n['emitted_ce_occupation'], 5)} |")
    out += ['', '## B. Effort per chain (full pool)', '', '| Family | Version | Solver | CPU s | Lloyd steps (sum over strengths) | '
            'Route evaluations | Line-search person events |', '|---|---|---|---|---|---|---|']
    for fam in ('PRC', 'HQ'):
        for v in C.VERSIONS:
            s = _j(R / 'source' / f'SOURCE_CHECK_V{v}.json')['runs']
            for sol in ('original', 'SV1', 'SV1_first'):
                r = s[f'{fam}|{sol}']
                ps = r['per_strength'].values()
                out.append(f"| {fam} | {v} | {sol} | {_f(r['cpu_s'], 1)} | {sum(x['lloyd_steps'] for x in ps)} | "
                           f"{sum(x['route_evaluations'] for x in ps)} | {sum(x['line_search_events'] for x in ps):,} |")
    out += ['', '## C. MODEL_FIT nested held-out: pair LOOKUP AUC and total NLL spend over the twin (both solvers, same folds and teachers)', '',
            '| Version | Strength | PRC original | PRC SV1 | HQ original | HQ SV1 |', '|---|---|---|---|---|---|']
    for v in C.VERSIONS:
        n = _j(R / 'nested' / f'NESTED_SOLVERS_V{v}.json')
        m, sp = n['means'], n['spend_over_twin']
        out.append(f"| {v} | twin | {_f(m['PRC_TWIN']['auc_pair'])} / 0 | | | |")
        for lam in GRID:
            cells = []
            for nm in (f'PRC@{lam}', f'PRCsv1@{lam}', f'HQ@{lam}', f'HQsv1@{lam}'):
                tot = sp[nm]['occ_nll'][0] + sp[nm]['inc_nll'][0]
                cells.append(f"{_f(m[nm]['auc_pair'])} / {_f(tot, 4, True)}")
            out.append(f"| {v} | {lam} | " + ' | '.join(cells) + ' |')
    rs = _j(R / 'decisions' / 'ROUTE_S_INPUT.json')
    from . import rules as RU
    s = RU.route_s(rs)
    out += ['', '## D. Route S (frozen `route_s`) and the advancement decision', '',
            '| Version | SV1 S2 point (spend) | Original S2 point | Bracket | Pair AUC difference vs bracket (se) | Spend difference vs '
            'bracket (se) | Pair AUC difference vs original S2 (se) |', '|---|---|---|---|---|---|---|']
    for v in C.VERSIONS:
        pv, nv = s['per_version'][v], rs['nested'][str(v)]
        out.append(f"| {v} | {nv['revised_point']} ({_f(nv['revised_spend'], 5)}) | {pv['original_s2']} | {pv['bracket']} | "
                   f"{_f(pv['d_auc_vs_bracket'][0], 4, True)} ({_f(pv['d_auc_vs_bracket'][1], 4)}) | {_f(pv['d_spend_vs_bracket'][0], 5, True)} "
                   f"({_f(pv['d_spend_vs_bracket'][1], 5)}) | {_f(pv['d_auc_vs_original_s2'][0], 4, True)} ({_f(pv['d_auc_vs_original_s2'][1], 4)}) |")
    adv = _j(R / 'decisions' / 'ADVANCEMENT.json')['result']
    out += ['', f"Pooled pair AUC difference vs bracket: {_f(s['pooled_d_auc_vs_bracket'][0], 4, True)} (mean se "
                f"{_f(s['pooled_d_auc_vs_bracket'][1], 4)}); recovery rationale {s['recovery_rationale']}; task rationale {s['task_rationale']}. "
                f"Route S: **{s['label']}**. Advancement: **{adv['label']}** (D {adv['labels']['D']['_']}, E {adv['labels']['E']['SV1']}, "
                f"S {adv['labels']['S']['SV1']}).", '']
    ee = _j(R / 'decisions' / 'EQUAL_EFFORT_ATTRIBUTION.json')['families']
    out += ['## E. Equal-effort attribution (descriptive; never a decision input)', '',
            '| Family | Cells where the finer candidate set alone helped (SV1_first < original) | Cells where best-improvement selection '
            'added (SV1 < SV1_first) | Cells where selection hurt |', '|---|---|---|---|']
    for fam in ('PRC', 'HQ'):
        c = ee[fam]['attribution']['counts']
        out.append(f"| {fam} | {c['resolution']} of 12 | {c['selection']} of 12 | {c['selection_hurts']} of 12 |")
    rp = {v: _j(R / 'replay' / f'P1_REPLAY_V{v}.json') for v in C.VERSIONS}
    out += ['', '## F. P1 replay (the previous campaign\'s nested P1 estimator rerun unchanged)', '',
            '| Version | Nested means compared | Largest difference from the record | Selection equal | Brackets equal | F4 diff (se), replay '
            '| Estimator unchanged |', '|---|---|---|---|---|---|---|']
    for v, r in rp.items():
        out.append(f"| {v} | {r['n_compared']} | {_f(r['max_abs_diff_recorded_nested_means'], 3)} | {r['selection_equal_recorded']} | "
                   f"{r['brackets_equal_recorded']} | {_f(r['F4']['diff_twin_minus_prc'], 5)} ({_f(r['F4']['se_boot'], 5)}) | "
                   f"{r['estimator_unchanged']} |")
    return out


def main():
    d = R / 'tables'
    d.mkdir(parents=True, exist_ok=True)
    for name, fn in (('OBJECTIVE_AUDIT_TABLES.md', audit_tables), ('EXACT_REFERENCE_TABLES.md', exact_tables),
                     ('SOLVER_COMPARISON_TABLES.md', solver_tables)):
        (d / name).write_text('\n'.join(fn()) + '\n')
    print('written', sorted(p.name for p in d.iterdir()))
    return 0


if __name__ == '__main__':
    sys.exit(main())
