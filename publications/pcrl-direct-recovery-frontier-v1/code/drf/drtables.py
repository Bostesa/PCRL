"""TABLES.md / TABLES.json of the direct-recovery frontier campaign (DRF1; coordinator; label-free: saved records only).

    python3 -m drf.drtables write

Usefulness on MODEL_SELECT (original 28 conditions), registered-cell recovery of every grid member, the paired comparisons of each
reading's candidate, the decisions, the MODEL_FIT in-sample and nested diagnostics, the optimistic constructions and the coarsening
path. Development evidence on reused people, for the declared readers only; intervals do not correct the adaptive search.
"""
from __future__ import annotations
import json
import sys

import numpy as np

from . import claims as CL
from . import common as C
from . import frontier as FR
from nrm import rules as NR

READINGS = (('DRF_V1', 'DRF1_V1', 'DR_AUC', ''), ('DRF_R1', 'DRF1_R1', 'DR_AUC_R1', 'R1_'), ('DRF_R2', 'DRF1_R2', 'DR_AUC_R2', 'R2_'))


def _f(x, d=4, sign=True):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return '-'
    return f'{x:+.{d}f}' if sign else f'{x:.{d}f}'


def write():
    T, md = {}, ['# Tables (campaign `pcrl_direct_recovery_frontier_v1`, DRF1)', '',
                 'Generated by `python3 -m drf.drtables write` from saved records. Development evidence on adaptively reused MODEL_SELECT '
                 'people, for the declared readers only; versions are procedure repeats sharing every training row and the MODEL_SELECT '
                 'people; intervals do not correct the adaptive search.', '']
    # 1. usefulness
    md += ['## 1. Usefulness on MODEL_SELECT (28 original conditions; per version: point pass, worst value / cap, men\'s and '
           'women\'s occupation guard, total NLL excess vs U0)', '',
           '| Release | V0 | V1 |', '|---|---|---|']
    pts = ['DR_AUC', 'DR_MI', 'DR_CTRL_LO', 'DR_CTRL_HI', 'DR_AUC_R1', 'DR_MI_R1', 'DR_CTRL_LO_R1', 'DR_CTRL_HI_R1', 'DR_AUC_R2', 'DR_MI_R2',
           'DR_CTRL_LO_R2', 'DR_CTRL_HI_R2']
    specs = {**{p: f'DR/{p}' for p in pts}, 'TWB_C64': 'SRCFRC:FA/TWB_C64', **{r: FR.REF_SPEC.get(r, f'REF:{r}') for r in FR.REFS}}
    T['usefulness'] = {}
    for name, spec in specs.items():
        ev = FR._eval(spec)
        cells = []
        for v in C.VERSIONS:
            u = FR._util(ev, v)
            T['usefulness'].setdefault(name, {})[v] = u
            cells.append('-' if u is None else f"{'pass' if u['g1_point_pass_this_version'] else 'FAIL ' + ','.join(u['failed'])} "
                                                f"{u['max_value_over_cap']:.3f} / men {_f(u['men_guard'])} / women {_f(u['women_guard'])} / "
                                                f"{_f(u['total_nll_excess_vs_U0'])}")
        if any(c != '-' for c in cells):
            md.append(f'| {name} | {cells[0]} | {cells[1]} |')
    md.append('')
    # 2. recovery and 3. comparisons per grid
    T['grids'], T['comparisons'] = {}, {}
    for rid, bank, cand, _ in READINGS:
        if not (C.RUNS / 'GRID' / bank).is_dir():
            continue
        g = CL.load_grid(bank)
        members = sorted({m for c in g['cells'].values() for m in c})
        md += [f'## 2. Recovery, bank {bank} (registered-cell mean SCORE AUC of the registered winner; V0 / V1)', '',
               '| Member | Pair | Income view | Occupation view |', '|---|---|---|---|']
        T['grids'][bank] = {}
        for m in members:
            row = {}
            for w in ('pair', 'income', 'occupation'):
                row[w] = [float(np.mean([g['cells'][c][m][w]['score_auc'] for c in NR.REGISTERED if c.startswith(f'S{v}')
                                          and c in g['cells'] and m in g['cells'][c]] or [np.nan])) for v in C.VERSIONS]
            T['grids'][bank][m] = row
            md.append(f"| {m} | {row['pair'][0]:.4f} / {row['pair'][1]:.4f} | {row['income'][0]:.4f} / {row['income'][1]:.4f} | "
                      f"{row['occupation'][0]:.4f} / {row['occupation'][1]:.4f} |")
        md += ['', f'## 3. Paired comparisons of {cand} (benefit = comparator AUC - candidate AUC; positive favours the candidate; '
                   f'se_agg; version means; screen; recipient gates)', '',
               '| Comparator | Benefit (se_agg) | V0 / V1 | Screen | Income gate | Occupation gate | 0.020 target screen |',
               '|---|---|---|---|---|---|---|']
        T['comparisons'][bank] = {}
        for comp, e in sorted(g['paired'].get(cand, {}).items()):
            cmp = NR.comparison(e)
            agg = cmp['benefit'].get('aggregate') or {}
            vm = [float(np.mean([e['pair']['cells'][c] for c in NR.REGISTERED if c.startswith(f'S{v}')])) for v in C.VERSIONS]
            tgt = NR.target_screen(e['pair']) if hasattr(NR, 'target_screen') else None
            tl = tgt.get('label') if isinstance(tgt, dict) else tgt
            T['comparisons'][bank][comp] = {'benefit': agg.get('mean'), 'se_agg': agg.get('se_agg'), 'version_means': vm,
                                            'screen': cmp['benefit']['label'], 'recipient_gate_pass': cmp['recipient_gate_pass'],
                                            'income': cmp['recipient']['income']['label'],
                                            'occupation': cmp['recipient']['occupation']['label'], 'target_screen': tl}
            md.append(f"| {comp} | {_f(agg.get('mean'))} ({_f(agg.get('se_agg'), sign=False)}) | {_f(vm[0])} / {_f(vm[1])} | "
                      f"{cmp['benefit']['label']} | {cmp['recipient']['income']['label']} | {cmp['recipient']['occupation']['label']} | "
                      f"{tl or '-'} |")
        md.append('')
    # 4. decisions
    md += ['## 4. Decisions (drf.rules, DRF1-rules-v1)', '', '| Reading | Registered | D1 | D2 | FC | TWIN | D3 | D4 | Stage | Class | D2R |',
           '|---|---|---|---|---|---|---|---|---|---|---|']
    ep = FR.endpoints()
    T['decisions'] = ep
    for rid, e in sorted(ep.items()):
        md.append(f"| {rid} | {e.get('registered')} {e.get('adaptive_tag') or ''} | {e['D1']} | {e['D2']} | {e['FC']} | {e['TWIN']} | "
                  f"{e['D3']} | {e['D4']} | {e['stage']} | {e['class']} | {e['D2R']} |")
    md.append('')
    # 5. MODEL_FIT diagnostics
    md += ['## 5. MODEL_FIT diagnostics (in-sample exact optimal-reader AUC on out-of-fold routing; nested held-out LOOKUP and spends)', '',
           '| Point | V | In-sample pair AUC* (estimated law / true-SEX law) | Binding | Nested LOOKUP pair / inc / occ | Nested spend: '
           'total NLL, occ NLL, men\'s Brier |', '|---|---|---|---|---|---|']
    rows = FR._fit_rows('', '') + FR._fit_rows('R1_', '_R1') + FR._fit_rows('R2_', '_R2')
    T['model_fit'] = [r for r in rows if r['source'] == 'fit']
    for r in rows:
        if r['source'] != 'fit':
            continue
        nl, ns = r.get('mf_nested_lookup_auc') or {}, r.get('mf_nested_spend') or {}
        md.append(f"| {r['point']} | {r['version']} | {r['mf_insample_estimated_auc']['auc_pair']:.4f} / "
                  f"{r['mf_insample_empirical_auc']['auc_pair']:.4f} | {r.get('binding')} | {nl.get('pair', float('nan')):.4f} / "
                  f"{nl.get('income', float('nan')):.4f} / {nl.get('occupation', float('nan')):.4f} | {_f(ns.get('total_nll'))}, "
                  f"{_f(ns.get('occ_nll'))}, {_f(ns.get('occ_brier_men'))} |")
    md += ['', '## 6. Optimistic MODEL_FIT diagnostics (OPT_S routes by the true SEX: not deployable)', '',
           '| Construction | V | In-sample pair / inc / occ AUC* (true-SEX law) | Within budget (in-sample) | Nested LOOKUP pair | '
           'Nested total NLL spend |', '|---|---|---|---|---|---|']
    T['optimistic'] = FR._opt_rows()
    for r in T['optimistic']:
        a = r['mf_insample_empirical_auc']
        md.append(f"| {r['point']} | {r['version']} | {a['auc_pair']:.4f} / {a['auc_inc']:.4f} / {a['auc_occ']:.4f} | {r['within_budget']} | "
                  f"{(r.get('mf_nested_lookup_auc') or {}).get('pair', float('nan')):.4f} | "
                  f"{_f((r.get('mf_nested_spend') or {}).get('total_nll'))} |")
    md.append('')
    C.write_json(C.RESULTS / 'TABLES.json', T)
    (C.RESULTS / 'TABLES.md').write_text('\n'.join(md) + '\n')
    return T


def main(argv=None):
    a = argv or sys.argv[1:]
    if not a or a[0] != 'write':
        raise SystemExit(__doc__)
    T = write()
    print(json.dumps({k: (len(v) if hasattr(v, '__len__') else v) for k, v in T.items()}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
