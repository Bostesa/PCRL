"""Independent byte replay of admitted role-only archives, without mixed source access.

This verifier does not import the custodian exporter. It reconstructs each ZIP
from its allowed role-only members using NumPy's public ``save`` API and fixed
ZIP metadata, then compares the 25 original hashes. Output is a new private
directory; the original export is never modified.
"""

from __future__ import annotations

import hashlib
import io
import json
import os
import sys
import zipfile
from pathlib import Path

import numpy as np


SHARED = Path(__file__).resolve().parent
CAMPAIGN = SHARED.parent
SOURCE = SHARED / ".private/role_export_v1"
DEST = SHARED / ".private/byte_replay_v1"
S4_REPORT = CAMPAIGN / "S4_ROLE_EXPORT_VERIFICATION.json"
S4_REPORT_SHA = "5d455806634fbe3046d5d6487f9b9c411c600344f72e1374c1d66f3c19ebd9e9"


def file_hash(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def replay() -> dict:
    if file_hash(S4_REPORT) != S4_REPORT_SHA or json.loads(S4_REPORT.read_text()).get("status") != "PASS":
        raise RuntimeError("S4 role-export admission is absent or changed")
    if DEST.exists():
        raise RuntimeError("private byte replay destination already exists")
    receipt = json.loads((SOURCE / "EXPORT_RECEIPT.json").read_text())
    if receipt.get("status") != "STAGED_FOR_INDEPENDENT_ADMISSION" or len(receipt.get("files", [])) != 25:
        raise RuntimeError("source export receipt mismatch")
    DEST.mkdir(parents=True, mode=0o700)
    checked = []
    for entry in receipt["files"]:
        relative = Path(entry["relative_path"])
        if relative.is_absolute() or ".." in relative.parts or relative.suffix != ".npz":
            raise RuntimeError("unsafe role-only relative path")
        source_file = SOURCE / relative
        target_file = DEST / relative
        if file_hash(source_file) != entry["sha256"]:
            raise RuntimeError("original role-only file changed")
        with zipfile.ZipFile(source_file) as archive:
            member_names = {x.filename for x in archive.infolist()}
        if member_names != {name + ".npy" for name in entry["members"]}:
            raise RuntimeError("original role-only member schema changed")
        with np.load(source_file, allow_pickle=False) as archive:
            arrays = {name: np.array(archive[name], copy=True) for name in entry["members"]}
        target_file.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(target_file, "w") as archive:
            for name in sorted(arrays):
                npy = io.BytesIO()
                np.save(npy, np.ascontiguousarray(arrays[name]), allow_pickle=False)
                info = zipfile.ZipInfo(name + ".npy", date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o600 << 16
                archive.writestr(info, npy.getvalue(), compresslevel=6)
        target_file.chmod(0o600)
        if file_hash(target_file) != entry["sha256"]:
            raise RuntimeError("role-only deterministic byte replay mismatch")
        checked.append({"relative_path": str(relative), "sha256": entry["sha256"]})
    result = {"schema": "pcrl-role-only-byte-replay-v1", "status": "PASS", "files": len(checked),
              "source_exporter_sha256": receipt["exporter_sha256"], "s4_report_sha256": S4_REPORT_SHA,
              "check": "all 25 role-only archives regenerated byte-identically from allowed private arrays; mixed source not opened"}
    path = DEST / "BYTE_REPLAY_RECEIPT.json"
    path.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    path.chmod(0o600)
    return result


if __name__ == "__main__":
    os.umask(0o077)
    try:
        result = replay()
    except BaseException as exc:
        print(f"BYTE_REPLAY_FAILED:{type(exc).__name__}", file=sys.stderr)
        raise SystemExit(1)
    print(json.dumps({"status": result["status"], "files": result["files"]}, sort_keys=True))
