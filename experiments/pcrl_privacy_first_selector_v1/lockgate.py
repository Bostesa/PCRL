"""PROTOCOL sections 7, 8 and 11: endpoint families, write-once lock, remote-verified gate.

The families are generated by the SC generator (`lock.enumerate_family`,
`capability_family`, `exact_zero_flags`) with this study's slots, P-route
clauses for every slot, and Bonferroni per family from the generated count.

Gate: the outer role may be opened only when (i) SELECTION_LOCK.json has the
expected SHA-256, (ii) it is committed on origin/<this branch> (git ls-remote +
merge-base + `git show` of the lock bytes), and (iii) the write-once unlock
receipt records that verified commit.  The receipt is re-verified on origin at
every gate call.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import subprocess
from typing import Mapping

from scipy.stats import norm

from experiments.pcrl_shared_context_release_v1 import audit_panel, lock as sc_lock, selection

from . import host, solve

ROOT = Path(__file__).resolve().parents[2]
STUDY = solve.STUDY
BRANCH = "research/pcrl-privacy-first-selector-v1"
RESULTS = ROOT / "results" / STUDY
LOCK_RELATIVE = f"results/{STUDY}/SELECTION_LOCK.json"
LOCK_PATH = ROOT / LOCK_RELATIVE
UNLOCK_PATH = RESULTS / "private" / "OUTER_UNLOCK.json"
SCHEMA = "pcrl-pfs-selection-lock-v1"
UNLOCK_SCHEMA = "pcrl-pfs-outer-unlock-v1"
ANCHORS = (0, 1, 2)
ALPHA = .05
BOOTSTRAP = {"draws": 10000, "seed": 20260926, "alpha": ALPHA,
             "resampling": "one multinomial over the union of household IDs across the three anchors",
             "estimator": "equal mean of per-anchor weighted ratios",
             "bounds": "normal approximation, two-sided Bonferroni within each family"}
STATEMENT = ("These results may meet the new predeclared numerical criteria, but remain exploratory "
             "development evidence because the assessment data informed this study's design. They "
             "cannot provide independent confirmation.")
PRIMARY_SLOTS = [
    {"id": "D", "arm": "P", "source_name": "D4", "comparators": ["D17"]},
    {"id": "R", "arm": "P", "source_name": "R4", "comparators": ["D17"]},
    {"id": "R_vs_D", "arm": "P", "source_name": "R4", "comparators": ["D4"]},
]
SECONDARY_SLOTS = [
    {"id": "NM4PF", "arm": "P", "source_name": "NM4PF", "comparators": ["D17", "D4", "R4"]},
    {"id": "D4_vs_controls", "arm": "P", "source_name": "D4", "comparators": ["DET_SEL4", "TASK_SEL4", "D1"]},
    {"id": "R4_vs_R1", "arm": "P", "source_name": "R4", "comparators": ["R1"]},
    {"id": "D1", "arm": "P", "source_name": "D1", "comparators": ["D17"]},
    {"id": "R1", "arm": "P", "source_name": "R1", "comparators": ["D17"]},
    {"id": "DET_SEL4", "arm": "P", "source_name": "DET_SEL4", "comparators": ["D17"]},
    {"id": "TASK_SEL4", "arm": "P", "source_name": "TASK_SEL4", "comparators": ["D17"]},
]
CAPABILITY_SLOTS = [{"id": "D", "arm": "P", "source_name": "D4"}, {"id": "R", "arm": "P", "source_name": "R4"}]
DECISION_RULES = {
    "ARM_D_MEETS_CRITERIA": "all 10 primary clauses of slot D (D4 vs D17) pass on the simultaneous upper bound",
    "ARM_R_MEETS_CRITERIA": "all 10 primary clauses of slot R (R4 vs D17) pass",
    "RANDOMIZATION_ADDS": "all 10 primary clauses of slot R_vs_D (R4 vs D4) pass",
    "LEAD_REPRODUCED": ("point estimates, D4 vs D17: AB/SEX <= -.002 in both weightings, task <= +.001 in both, "
                        "each of the other six recovery contrasts <= +.001"),
}


def _sha(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _hex(value, size) -> bool:
    return isinstance(value, str) and len(value) == size and all(c in "0123456789abcdef" for c in value)


def _manifest(endpoints, scope):
    m = len(endpoints)
    return {"schema": 1, "n_endpoints": m, "endpoints": endpoints,
            "critical_value_two_sided": float(norm.isf(ALPHA / (2 * m))) if m else None,
            "multiplicity": "two-sided Bonferroni over exactly this generated list",
            "exact_zero_same_route_count": sum(e["exact_zero_same_route"] for e in endpoints),
            "scope": scope}


def generate(alias_of: Mapping[str, str]) -> dict:
    primary = sc_lock.enumerate_family(PRIMARY_SLOTS, alias_of={}, family="primary")
    secondary = sc_lock.enumerate_family(SECONDARY_SLOTS, alias_of=alias_of, family="secondary")
    capability = sc_lock.capability_family(CAPABILITY_SLOTS)
    return {"primary": primary, "secondary": secondary, "capability": capability}


def build_lock(reports: Mapping[int, Mapping], pins: Mapping[str, Mapping], *, code_commit: str,
               extra_pins: Mapping[str, str], prior_lock: Mapping, prior_lock_sha256: str) -> dict:
    mappings = {a: reports[a]["logical_to_canonical"] for a in ANCHORS}
    names = sorted({n for m in mappings.values() for n in m})
    if set(names) != set(host.DECLARED):
        raise ValueError("inner panels do not declare exactly the registered releases")
    alias_of = selection.global_aliases(mappings, names)
    families = generate(alias_of)
    for endpoints in families.values():
        sc_lock.exact_zero_flags(endpoints, reports)
    manifests = {"family_manifest": _manifest(families["primary"], "primary: registered decision rules (PROTOCOL 8)"),
                 "secondary_manifest": _manifest(families["secondary"], "descriptive, separately corrected; never part of a pass"),
                 "capability_manifest": _manifest(families["capability"], "separate H-capability family")}
    anchors = {}
    for a in ANCHORS:
        anchors[str(a)] = {"inner_panel_complete_sha256": pins[str(a)]["inner_panel_complete_sha256"],
                           "inner_audit_sha256": pins[str(a)]["inner_audit_sha256"],
                           "index_sha256": pins[str(a)]["index_sha256"],
                           "logical_to_canonical": dict(mappings[a]),
                           "releases": {rid: payload["source"] for rid, payload in reports[a]["releases"].items()}}
    if len({pins[str(a)]["index_sha256"] for a in ANCHORS}) != 1:
        raise ValueError("inner panels used different input indexes")
    pos = prior_lock["positive_controls"]
    return {"schema": SCHEMA, "status": "LOCKED", "study": STUDY, "branch": BRANCH,
            "assessment_year": 2018, "outer_assessment_authorized": True,
            "registered_statement": STATEMENT,
            "created_utc": datetime.now(timezone.utc).isoformat(), "code_commit": code_commit,
            "pins": dict(extra_pins),
            "declared_releases": list(host.DECLARED), "alias_of": alias_of,
            "primary_slots": PRIMARY_SLOTS, "secondary_slots": SECONDARY_SLOTS,
            "capability_slots": CAPABILITY_SLOTS, **manifests,
            "manifest_sha256": {k: sc_lock.manifest_sha256(v) for k, v in manifests.items()},
            "decision_rules": DECISION_RULES, "bootstrap": BOOTSTRAP, "anchors": anchors,
            "positive_controls": pos, "positive_controls_source_lock_sha256": prior_lock_sha256,
            "audit_uninformative": sorted(k for k, v in pos.items() if not v["detected"]),
            "outer_access": ("only via lockgate.verify_outer_gate after this file is committed, pushed and "
                             "remote-verified and private/OUTER_UNLOCK.json is written")}


def verify_lock_structure(lock: Mapping) -> None:
    if lock.get("schema") != SCHEMA or lock.get("status") != "LOCKED" or lock.get("study") != STUDY:
        raise PermissionError("not this study's lock")
    if (lock["primary_slots"] != PRIMARY_SLOTS or lock["secondary_slots"] != SECONDARY_SLOTS
            or lock["capability_slots"] != CAPABILITY_SLOTS):
        raise PermissionError("locked slots differ from the registered slots")
    generated = generate(lock["alias_of"])
    for name, key in (("family_manifest", "primary"), ("secondary_manifest", "secondary"),
                      ("capability_manifest", "capability")):
        stored = lock[name]
        strip = [{k: v for k, v in e.items() if k != "exact_zero_same_route"} for e in stored["endpoints"]]
        if strip != generated[key] or stored["n_endpoints"] != len(generated[key]):
            raise PermissionError(f"{name} differs from the family generated from the slots")
        if lock["manifest_sha256"][name] != sc_lock.manifest_sha256(stored):
            raise PermissionError(f"{name} hash differs")


def _git(*args, repo=ROOT) -> str:
    return subprocess.check_output(["git", *args], cwd=repo, text=True, stderr=subprocess.PIPE)


def remote_lock_check(commit: str, expected_sha256: str, *, repo=ROOT) -> dict:
    if not _hex(commit, 40) or not _hex(expected_sha256, 64):
        raise PermissionError("40-hex commit and 64-hex lock SHA-256 required")
    listing = _git("ls-remote", "origin", f"refs/heads/{BRANCH}", repo=repo).split()
    if not listing or not _hex(listing[0], 40):
        raise PermissionError(f"origin/{BRANCH} is not visible")
    tip = listing[0]
    _git("fetch", "-q", "origin", f"refs/heads/{BRANCH}", repo=repo)
    if subprocess.run(["git", "merge-base", "--is-ancestor", commit, tip], cwd=repo,
                      capture_output=True).returncode:
        raise PermissionError("lock commit is not on the pushed study branch")
    blob = subprocess.check_output(["git", "show", f"{commit}:{LOCK_RELATIVE}"], cwd=repo)
    if hashlib.sha256(blob).hexdigest() != expected_sha256:
        raise PermissionError("SELECTION_LOCK.json at the pushed commit differs from the expected SHA-256")
    return {"branch": BRANCH, "remote_tip": tip, "remote_commit_sha": commit,
            "lock_relative_path": LOCK_RELATIVE, "lock_sha256_at_commit": expected_sha256}


def write_unlock(expected_sha256: str, commit: str, *, unlock_path: Path | None = None) -> dict:
    target = unlock_path or UNLOCK_PATH
    if target.exists():
        raise FileExistsError("outer unlock receipt is write-once")
    if _sha(LOCK_PATH) != expected_sha256:
        raise PermissionError("local SELECTION_LOCK.json differs from the expected SHA-256")
    verify_lock_structure(json.loads(LOCK_PATH.read_text()))
    evidence = remote_lock_check(commit, expected_sha256)
    receipt = {"schema": UNLOCK_SCHEMA, "lock_sha256": expected_sha256, "remote_verified": True,
               "branch": BRANCH, "remote_commit_sha": commit,
               "verified_utc": datetime.now(timezone.utc).isoformat(), "evidence": evidence}
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(target.name + f".tmp.{os.getpid()}")
    temporary.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    os.replace(temporary, target)
    return receipt


def verify_outer_gate(selection_lock_path, expected_sha256: str, *, lock_path: Path | None = None,
                      unlock_path: Path | None = None) -> dict:
    registered = (lock_path or LOCK_PATH).resolve()
    path = Path(selection_lock_path).resolve()
    if path != registered or not _hex(expected_sha256, 64):
        raise PermissionError("registered selection lock path and SHA-256 required")
    if not path.is_file() or _sha(path) != expected_sha256:
        raise PermissionError("selection lock is absent or differs from the expected SHA-256")
    lock = json.loads(path.read_text())
    verify_lock_structure(lock)
    if lock.get("outer_assessment_authorized") is not True:
        raise PermissionError("outer assessment not authorized by the lock")
    unlock_file = unlock_path or UNLOCK_PATH
    if not unlock_file.is_file():
        raise PermissionError("remote-verified outer unlock receipt is absent")
    unlock = json.loads(unlock_file.read_text())
    if (unlock.get("schema") != UNLOCK_SCHEMA or unlock.get("lock_sha256") != expected_sha256 or
            unlock.get("remote_verified") is not True or unlock.get("branch") != BRANCH):
        raise PermissionError("outer unlock was not remotely verified")
    remote_lock_check(unlock["remote_commit_sha"], expected_sha256)
    return lock


def lock_from_panels(panels_root: Path, code_commit: str, out: Path = LOCK_PATH) -> dict:
    reports, pins = {}, {}
    for a in ANCHORS:
        root = Path(panels_root) / f"a{a}"
        reports[a] = audit_panel.verify_complete(root)
        pins[str(a)] = {"inner_panel_complete_sha256": _sha(root / "COMPLETE.json"),
                        "inner_audit_sha256": _sha(root / "INNER_AUDIT.json"),
                        "index_sha256": reports[a]["index_sha256"]}
    prior_path = ROOT / "results" / "pcrl_shared_context_release_v1" / "SELECTION_LOCK.json"
    prior = json.loads(prior_path.read_text())
    extra = {name: _sha(RESULTS / name) for name in
             ("PROTOCOL.md", "BASIS_MANIFEST.json", "DECISION_VARIATION_INNER.json", "INNER_REPORT.json",
              "SOLVE_REPORTS.json")}
    if (RESULTS / "PROTOCOL_AMENDMENTS.md").is_file():
        extra["PROTOCOL_AMENDMENTS.md"] = _sha(RESULTS / "PROTOCOL_AMENDMENTS.md")
    lock = build_lock(reports, pins, code_commit=code_commit, extra_pins=extra,
                      prior_lock=prior, prior_lock_sha256=_sha(prior_path))
    if out.exists():
        raise FileExistsError("SELECTION_LOCK.json is write-once")
    out.write_text(json.dumps(lock, indent=2, sort_keys=True, allow_nan=False) + "\n")
    return lock


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="action", required=True)
    item = sub.add_parser("lock"); item.add_argument("--panels", required=True)
    item.add_argument("--code-commit", required=True)
    item = sub.add_parser("unlock"); item.add_argument("--lock-sha256", required=True)
    item.add_argument("--commit", required=True)
    args = parser.parse_args(argv)
    if args.action == "lock":
        lock = lock_from_panels(Path(args.panels), args.code_commit)
        value = {"sha256": _sha(LOCK_PATH),
                 "n_endpoints": {k: lock[k]["n_endpoints"] for k in
                                 ("family_manifest", "secondary_manifest", "capability_manifest")},
                 "z": {k: lock[k]["critical_value_two_sided"] for k in
                       ("family_manifest", "secondary_manifest", "capability_manifest")},
                 "alias_of": lock["alias_of"]}
    else:
        value = write_unlock(args.lock_sha256, args.commit)
    print(json.dumps(value, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
